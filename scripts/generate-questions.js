#!/usr/bin/env node
/**
 * Incrementally generates Hebrew Calculus I game questions from PDF textbooks.
 *
 * Each run processes ONE chunk of the PDF (≤35% of the 200K token context window)
 * then saves progress so the next run continues where it left off.
 * Two Claude calls per run: generate → validate. Both stay well under 50% of limit.
 *
 * Usage:
 *   node generate-questions.js path/to/textbook.pdf   # start new file
 *   node generate-questions.js                         # resume from progress
 *
 * Requires: ANTHROPIC_API_KEY env variable
 * Output:   ../data/generated-topics.js  (merged into game on page load)
 */

'use strict';

const Anthropic = require('@anthropic-ai/sdk');
const fs = require('fs');
const path = require('path');
const pdfParse = require('pdf-parse');
const { jsonrepair } = require('jsonrepair');

const ROOT_DIR = path.join(__dirname, '..');
const PROGRESS_FILE = path.join(__dirname, '.progress.json');
const CONFIG_FILE = path.join(__dirname, 'config.json');
const DATA_FILE = path.join(ROOT_DIR, 'data', 'generated-topics-data.json');
const OUTPUT_JS = path.join(ROOT_DIR, 'data', 'generated-topics.js');

function loadConfig() {
  if (!fs.existsSync(CONFIG_FILE)) return {};
  return JSON.parse(fs.readFileSync(CONFIG_FILE, 'utf8'));
}

// Claude Sonnet 4.6 has a 200K token context window, but the free tier
// rate-limits to 30K input tokens/minute. We keep chunks under 25K so each
// call (chunk + system prompt + wrapper) stays well within that limit.
const MAX_CONTEXT_TOKENS = 200_000;
const CHUNK_TOKEN_BUDGET = 25_000;
const MAX_OUTPUT_TOKENS = 8_192;

// Rough estimator: 1 token ≈ 4 characters
function estimateTokens(text) {
  return Math.ceil(text.length / 4);
}

// ─── Progress ────────────────────────────────────────────────────────────────

function loadProgress() {
  if (!fs.existsSync(PROGRESS_FILE)) return null;
  return JSON.parse(fs.readFileSync(PROGRESS_FILE, 'utf8'));
}

function saveProgress(data) {
  fs.writeFileSync(PROGRESS_FILE, JSON.stringify(data, null, 2), 'utf8');
}

function clearProgress() {
  if (fs.existsSync(PROGRESS_FILE)) fs.unlinkSync(PROGRESS_FILE);
}

// ─── Chunking ────────────────────────────────────────────────────────────────

/**
 * Split raw PDF text into chunks that each fit within maxTokens.
 * Splits on paragraph breaks so sentences are never cut mid-way.
 */
function splitIntoChunks(text, maxTokens) {
  const chunks = [];
  const paragraphs = text.split(/\n{2,}/);
  let current = '';

  for (const para of paragraphs) {
    const trimmed = para.trim();
    if (!trimmed) continue;
    const candidate = current ? `${current}\n\n${trimmed}` : trimmed;
    if (estimateTokens(candidate) > maxTokens && current) {
      chunks.push(current.trim());
      current = trimmed;
    } else {
      current = candidate;
    }
  }
  if (current.trim()) chunks.push(current.trim());
  return chunks;
}

// ─── Persistent topic store ───────────────────────────────────────────────────

function loadStoredTopics() {
  if (!fs.existsSync(DATA_FILE)) return [];
  return JSON.parse(fs.readFileSync(DATA_FILE, 'utf8'));
}

function saveStoredTopics(incoming) {
  const stored = loadStoredTopics();

  for (const topic of incoming) {
    const idx = stored.findIndex(t => t.id === topic.id);
    if (idx >= 0) {
      // Deduplicate by prompt before merging
      const existingPrompts = new Set(stored[idx].questions.map(q => q.prompt));
      const fresh = topic.questions.filter(q => !existingPrompts.has(q.prompt));
      stored[idx].questions.push(...fresh);
    } else {
      stored.push(topic);
    }
  }

  fs.writeFileSync(DATA_FILE, JSON.stringify(stored, null, 2), 'utf8');
  rewriteOutputJs(stored);
}

/**
 * Regenerate the browser-loadable JS from the stored JSON.
 * The IIFE merges topics into the existing TOPICS global at page load.
 */
function rewriteOutputJs(topics) {
  const json = JSON.stringify(topics, null, 2);
  const content =
`// Auto-generated by scripts/generate-questions.js — do not edit manually.
// Re-run the script to add more questions from a PDF textbook.
(function () {
  var _generated = ${json};
  _generated.forEach(function (t) {
    var existing = TOPICS.find(function (x) { return x.id === t.id; });
    if (existing) {
      existing.questions.push.apply(existing.questions, t.questions);
    } else {
      TOPICS.push(t);
    }
  });
})();
`;
  fs.writeFileSync(OUTPUT_JS, content, 'utf8');
}

// ─── Claude calls ────────────────────────────────────────────────────────────

const GENERATION_SYSTEM = `You are an expert educator creating Hebrew-language game questions for a Calculus I proof-training game.

The game supports four question types:
• "order"  — Drag-and-drop to arrange proof steps.
  Required fields: steps (string[]), answer (number[] — the correct order of step indices)
• "mcq"    — Multiple choice with exactly 4 options.
  Required fields: choices (string[4]), answer (number 0–3)
• "tf"     — True / False.
  Required fields: answer (boolean)
• "fill"   — Fill in the blank; use ___ in the prompt for the blank.
  Required fields: answer (short string), hint (string)

Every question also needs: type, prompt, explanation (Hebrew, explains the correct answer).
• proof.statement MUST be a complete LaTeX expression wrapped in $...$ (e.g. "$\\lim_{x\\to a}f(x)=L$"). Never output raw LaTeX without dollar-sign delimiters.

Rules:
- All text (prompt, choices, hint, explanation, title, sub, idea) must be in Hebrew.
- Use LaTeX for mathematics: $\\varepsilon > 0$, $\\lim_{x \\to a} f(x)$, etc.
- Return ONLY a valid JSON array — no prose, no markdown fences.`;

async function withRetry(fn, label) {
  const delays = [60, 90, 120];
  for (let attempt = 0; attempt <= delays.length; attempt++) {
    try {
      return await fn();
    } catch (err) {
      const isRateLimit = err.status === 429 || (err.message && err.message.includes('rate_limit'));
      if (isRateLimit && attempt < delays.length) {
        const wait = delays[attempt];
        console.log(`      Rate limit hit — waiting ${wait}s before retry ${attempt + 1}/${delays.length}...`);
        await new Promise(r => setTimeout(r, wait * 1000));
      } else {
        throw err;
      }
    }
  }
}

async function generateQuestions(client, chunk) {
  const prompt = `Based on the following textbook excerpt, create 4–6 game questions that cover the main mathematical concepts.

Return a JSON array of topic objects in this exact shape:
[
  {
    "id": "unique-kebab-case-id",
    "icon": "one emoji",
    "title": "Hebrew topic title",
    "sub": "Hebrew one-line description",
    "badge": "Hebrew badge label",
    "modes": ["mcq", "tf", "fill", "order"],
    "proof": {
      "title": "Hebrew proof title",
      "statement": "LaTeX mathematical statement",
      "idea": "Hebrew intuitive explanation"
    },
    "questions": [ ... ]
  }
]

TEXTBOOK EXCERPT:
${chunk}`;

  const response = await withRetry(() => client.messages.create({
    model: 'claude-sonnet-4-6',
    max_tokens: MAX_OUTPUT_TOKENS,
    system: GENERATION_SYSTEM,
    messages: [{ role: 'user', content: prompt }],
  }), 'generation');

  const raw = response.content[0].text.trim();
  const match = raw.match(/\[[\s\S]*\]/);
  if (!match) throw new Error('Generation response contained no JSON array');

  return {
    topics: JSON.parse(jsonrepair(match[0])),
    inputTokens: response.usage?.input_tokens ?? estimateTokens(prompt),
  };
}

const VALIDATION_SYSTEM = `You are a rigorous validator for Hebrew Calculus I game questions.

For each question verify:
1. The answer is mathematically correct.
2. Hebrew text is grammatically sound.
3. LaTeX is valid (properly escaped backslashes, balanced dollars).
4. All required fields are present for the question type.
5. "order" — answer indices are a valid permutation of [0..steps.length-1].
6. "mcq"   — answer is an integer 0–3 and choices has exactly 4 entries.
7. "fill"  — the answer string fits naturally in the blank.

Fix issues in place. Drop questions that are fundamentally wrong and unfixable.
Return ONLY the corrected JSON array — no prose, no markdown fences.`;

async function validateQuestions(client, topics) {
  const prompt = `Validate and fix these Calculus I game questions. Return only the corrected JSON array.\n\n${JSON.stringify(topics, null, 2)}`;

  const response = await withRetry(() => client.messages.create({
    model: 'claude-sonnet-4-6',
    max_tokens: MAX_OUTPUT_TOKENS,
    system: VALIDATION_SYSTEM,
    messages: [{ role: 'user', content: prompt }],
  }), 'validation');

  const raw = response.content[0].text.trim();
  const match = raw.match(/\[[\s\S]*\]/);
  if (!match) throw new Error('Validation response contained no JSON array');

  return {
    topics: JSON.parse(jsonrepair(match[0])),
    inputTokens: response.usage?.input_tokens ?? estimateTokens(prompt),
  };
}

// ─── Core processing ─────────────────────────────────────────────────────────

async function processFile(pdfPath, startChunkIndex, pdfIndex) {
  const client = new Anthropic();

  console.log(`Reading PDF: ${path.basename(pdfPath)}`);
  const buffer = fs.readFileSync(pdfPath);
  const pdf = await pdfParse(buffer);

  const totalTokens = estimateTokens(pdf.text);
  console.log(`${pdf.numpages} pages  |  ~${totalTokens.toLocaleString()} tokens total`);

  const chunks = splitIntoChunks(pdf.text, CHUNK_TOKEN_BUDGET);
  console.log(`Split into ${chunks.length} chunks (budget: ${CHUNK_TOKEN_BUDGET.toLocaleString()} tokens each)`);

  if (startChunkIndex >= chunks.length) {
    console.log('All chunks have been processed for this file.');
    clearProgress();
    return;
  }

  const chunk = chunks[startChunkIndex];
  const chunkTokens = estimateTokens(chunk);
  const pct = ((chunkTokens / MAX_CONTEXT_TOKENS) * 100).toFixed(1);

  console.log(`\nChunk ${startChunkIndex + 1} / ${chunks.length}  |  ~${chunkTokens.toLocaleString()} tokens  (${pct}% of 200K — well under 50% cap)`);

  // ── Step 1: Generate ────────────────────────────────────────────────────────
  console.log('\n[1/2] Generating questions...');
  let genResult;
  try {
    genResult = await generateQuestions(client, chunk);
    const n = genResult.topics.reduce((s, t) => s + t.questions.length, 0);
    console.log(`      ${n} questions across ${genResult.topics.length} topic(s)  (input tokens used: ${genResult.inputTokens.toLocaleString()})`);
  } catch (err) {
    console.error('      Generation failed:', err.message);
    throw err;
  }

  // ── Step 2: Validate ────────────────────────────────────────────────────────
  console.log('[2/2] Validating questions...');
  let valResult;
  try {
    valResult = await validateQuestions(client, genResult.topics);
    const n = valResult.topics.reduce((s, t) => s + t.questions.length, 0);
    console.log(`      ${n} questions passed validation  (input tokens used: ${valResult.inputTokens.toLocaleString()})`);
  } catch (err) {
    console.warn('      Validation step failed — saving unvalidated questions:', err.message);
    valResult = { topics: genResult.topics, inputTokens: 0 };
  }

  // ── Step 3: Save ────────────────────────────────────────────────────────────
  console.log('\nSaving to data/generated-topics.js...');
  saveStoredTopics(valResult.topics);
  const savedN = valResult.topics.reduce((s, t) => s + t.questions.length, 0);
  console.log(`Saved ${savedN} questions.`);

  // ── Step 4: Update progress ──────────────────────────────────────────────────
  const next = startChunkIndex + 1;
  const remaining = chunks.length - next;

  if (remaining > 0) {
    saveProgress({
      sourceFile: pdfPath,
      pdfIndex,
      totalChunks: chunks.length,
      nextChunkIndex: next,
      lastProcessedAt: new Date().toISOString(),
      remaining,
    });
    console.log(`\nProgress saved. ${remaining} chunk(s) remaining in this book.`);
    console.log(`Run "node generate-questions.js" to process chunk ${next + 1}/${chunks.length}.`);
    return false;
  } else {
    console.log('\nAll chunks processed for this book!');
    clearProgress();
    return true;
  }
}

// ─── Entry point ─────────────────────────────────────────────────────────────

async function main() {
  const args = process.argv.slice(2);
  const config = loadConfig();

  // Apply API key from config.json if not already in environment
  if (config.apiKey && config.apiKey !== 'sk-ant-YOUR-KEY-HERE') {
    process.env.ANTHROPIC_API_KEY = process.env.ANTHROPIC_API_KEY || config.apiKey;
  }

  // Resolve the list of PDFs from config (supports both pdfPaths array and legacy pdfPath)
  const pdfPaths = config.pdfPaths
    ? config.pdfPaths
    : config.pdfPath ? [config.pdfPath] : [];

  function advanceToNextBook(currentIndex) {
    const nextIndex = currentIndex + 1;
    if (!pdfPaths[nextIndex]) {
      console.log('\nAll books fully processed!');
      return;
    }
    const nextPath = path.resolve(pdfPaths[nextIndex]);
    if (!fs.existsSync(nextPath)) {
      console.error(`\nNext book not found: ${nextPath}`);
      return;
    }
    saveProgress({
      sourceFile: nextPath,
      pdfIndex: nextIndex,
      totalChunks: null,
      nextChunkIndex: 0,
      lastProcessedAt: new Date().toISOString(),
      remaining: null,
    });
    console.log(`\nBook ${nextIndex + 1}/${pdfPaths.length} queued: ${path.basename(nextPath)}`);
    console.log('Run "node generate-questions.js" to start it.');
  }

  if (args.length > 0) {
    // Explicit path passed on the command line
    const pdfPath = path.resolve(args[0]);
    if (!fs.existsSync(pdfPath)) {
      console.error(`File not found: ${pdfPath}`);
      process.exit(1);
    }
    if (!pdfPath.toLowerCase().endsWith('.pdf')) {
      console.error('Argument must be a .pdf file');
      process.exit(1);
    }
    await processFile(pdfPath, 0, 0);

  } else {
    // No argument — resume progress or start the first book
    const progress = loadProgress();

    if (progress) {
      if (!fs.existsSync(progress.sourceFile)) {
        console.error(`Saved PDF no longer exists: ${progress.sourceFile}`);
        console.error('Update pdfPaths in scripts/config.json and run again.');
        clearProgress();
        process.exit(1);
      }
      const pdfIndex = progress.pdfIndex ?? 0;
      const bookLabel = pdfPaths.length > 1 ? `book ${pdfIndex + 1}/${pdfPaths.length} — ` : '';
      console.log(`Resuming: ${bookLabel}${path.basename(progress.sourceFile)}`);
      if (progress.totalChunks) {
        console.log(`Progress: chunk ${progress.nextChunkIndex + 1}/${progress.totalChunks}  (${progress.remaining} remaining)`);
        console.log(`Last run: ${progress.lastProcessedAt}`);
      }
      const done = await processFile(progress.sourceFile, progress.nextChunkIndex, pdfIndex);
      if (done) advanceToNextBook(pdfIndex);

    } else if (pdfPaths.length > 0) {
      const pdfPath = path.resolve(pdfPaths[0]);
      if (!fs.existsSync(pdfPath)) {
        console.error(`PDF not found: ${pdfPath}`);
        console.error('Edit pdfPaths in scripts/config.json');
        process.exit(1);
      }
      const bookLabel = pdfPaths.length > 1 ? `book 1/${pdfPaths.length} — ` : '';
      console.log(`Starting ${bookLabel}${path.basename(pdfPath)}`);
      const done = await processFile(pdfPath, 0, 0);
      if (done) advanceToNextBook(0);

    } else {
      console.error('Nothing to do. Either:');
      console.error('  1. Set pdfPaths in scripts/config.json, then run: node generate-questions.js');
      console.error('  2. Pass the path directly:                         node generate-questions.js path/to/file.pdf');
      process.exit(1);
    }
  }
}

main().catch(err => {
  console.error('Fatal:', err.message);
  process.exit(1);
});
